/* Fetch a few at a time rather than all at once.

   The install fires while the visitor is still loading the page they asked
   for. Firing thirty-odd requests at that moment competes with the images and
   type they are actually waiting on, and on a phone with two bars - the whole
   reason this worker exists - it is the connection least able to take it.
   Six at a time fills the cache without ever being the reason something else
   on the page timed out. */
function fill(list, required) {
  return caches.open(CACHE).then(function (c) {
    var queue = list.slice(), failed = [];

    function next() {
      var u = queue.shift();
      if (u === undefined) return Promise.resolve();
      return c.match(u).then(function (have) {
        if (have) return null;                       // already got it
        return c.add(new Request(u, { cache: 'reload' }));
      }).catch(function (err) {
        failed.push(u + ' (' + (err && err.message ? err.message : err) + ')');
      }).then(next);
    }

    var lanes = [];
    for (var i = 0; i < 6; i++) lanes.push(next());
    return Promise.all(lanes).then(function () {
      if (!failed.length) return true;
      // never fail silently: a worker that thinks it is complete when it is
      // not will serve a broken site offline and nobody will know why
      console.warn('[fekc sw] ' + failed.length + ' of ' + list.length +
                   ' not cached:', failed);
      if (required) throw new Error('shell incomplete: ' + failed.join(', '));
      return false;
    });
  });
}

self.addEventListener('install', function (e) {
  // Only the shell blocks the install. If it cannot be cached the install
  // fails on purpose, the previous worker and its cache stay exactly as they
  // were, and the browser retries on the next visit.
  e.waitUntil(fill(SHELL, true).then(function () { return self.skipWaiting(); }));
});

self.addEventListener('activate', function (e) {
  e.waitUntil(
    caches.keys().then(function (keys) {
      return Promise.all(keys.map(function (k) {
        if (k !== CACHE && k.indexOf('fekc-') === 0) return caches.delete(k);
      }));
    }).then(function () { return self.clients.claim(); })
     .then(function () {
       // the rest of the pages, once the visitor is no longer waiting on us.
       // fill() skips anything already cached, so this doubles as the repair
       // pass for an earlier attempt that only got half way.
       return fill(REST, false);
     })
  );
});

/* A worker can be stopped and restarted at any time, so the top-up above may
   never have finished. Re-run it on the first navigation of a new worker
   lifetime: cheap when there is nothing to do, and it means a fill that was
   interrupted on a bad connection is picked up rather than abandoned. */
var toppedUp = false;
function topUp() {
  if (toppedUp) return;
  toppedUp = true;
  fill(REST, false);
}

/* Pages: the network first, the cache only if the network cannot answer.

   The obvious alternative - serve the cache at once and refresh behind the
   scenes - makes every page load instant, but it also means the first view
   after any rebuild is the version before it. On a site whose whole job is
   telling somebody a date, a fee and a set of directions, handing them last
   week's fee table once per deploy is exactly the failure the rebuild exists
   to prevent. Pages are a few kB compressed, so asking for one is cheap.

   The compromise is the timeout. If the network has not answered in two and a
   half seconds - the lane outside the circuit on a race morning - the cached
   copy is served rather than leaving somebody looking at a white screen, and
   the network response still updates the cache when it eventually lands. */
var PAGE_TIMEOUT = 2500;

function page(req) {
  var cached = caches.match(req, { ignoreSearch: true });

  var net = fetch(req).then(function (res) {
    if (res && res.ok) {
      var copy = res.clone();
      caches.open(CACHE).then(function (c) { c.put(req, copy); })
        .catch(function () {});
    }
    return res;
  });

  return new Promise(function (resolve) {
    var settled = false;
    function done(r) { if (!settled && r) { settled = true; resolve(r); } }

    net.then(done, function () {
      // offline. Whatever we hold for this page, or failing that the home
      // page, which at least carries the whole navigation
      cached.then(function (hit) {
        if (hit) return done(hit);
        caches.match('/').then(function (home) { done(home || Response.error()); });
      });
    });

    setTimeout(function () {
      if (settled) return;
      cached.then(function (hit) { done(hit); });   // no copy: keep waiting
    }, PAGE_TIMEOUT);
  });
}

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET') return;

  var url;
  try { url = new URL(req.url); } catch (err) { return; }
  if (url.origin !== self.location.origin) return;   // the Google map, once asked for

  // The notice is the one thing that must never be stale: it is how the club
  // says a meeting is off. Straight to the network, and if that fails the
  // page simply has no banner, which is the right failure mode.
  if (url.pathname.indexOf('/data/notice.json') !== -1) return;

  // Pages: serve the cached copy at once, refresh it in the background. The
  // banner and the cancellations come from notice.json on every load, so a
  // page one deploy behind still tells the truth about today.
  if (req.mode === 'navigate' || /\.html$|\/$/.test(url.pathname)) {
    topUp();
    e.respondWith(page(req));
    return;
  }

  // Everything else same-origin - styles, script, type, photographs. All of it
  // is served with a year of cache headers and none of it changes without a
  // rebuild, so the cached copy is the answer.
  //
  // The photographs are not precached, so most of these are a miss and go to
  // the network. Once respondWith has been called the browser will not fall
  // back to its own networking for us, so anything that throws here is a
  // broken image on the page rather than a retry: catch it, try the cache
  // once more, and only then give up.
  e.respondWith(
    caches.match(req).then(function (hit) {
      if (hit) return hit;
      return fetch(req).then(function (res) {
        if (res && res.ok && res.type === 'basic') {
          var copy = res.clone();
          caches.open(CACHE).then(function (c) { c.put(req, copy); })
            .catch(function () { /* 206s and quota errors are not our problem */ });
        }
        return res;
      }).catch(function () {
        return caches.match(req, { ignoreSearch: true }).then(function (late) {
          return late || Response.error();
        });
      });
    })
  );
});
